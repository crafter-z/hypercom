// ==================== 初始化 ====================
// 启动时从 store 读取语言配置；config.language 已是 'zh-CN'/'en-US'。
const initialLang = useAppStore.getState().config?.language || 'zh-CN';

i18n.use(initReactI18next).init({
  resources,
  lng: initialLang,
  fallbackLng: 'zh-CN',
  keySeparator: false, // 扁平 dotted key
  nsSeparator: false,  // 不使用命名空间分隔
  interpolation: {
    // React 已自动转义，关闭 i18next 的转义避免双重处理
    escapeValue: false,
  },
});

// ==================== 语言切换效果 ====================
// 监听 store 中的 config.language 变化并同步到 i18next。
// Zustand v5 原生 subscribe(listener) 只接收整个 state；
// 这里在 listener 内部 diff language 字段。
let currentLang = initialLang;
useAppStore.subscribe((state) => {
  const newLang = state.config?.language;
  if (newLang && newLang !== currentLang) {
    currentLang = newLang;
    i18n.changeLanguage(newLang).catch((e) => console.error('[i18n] changeLanguage failed:', e));
  }
});

